// PT Unit 62 — Os planos e as intenções (slot: plans-intentions) — B1
// ─────────────────────────────────────────────────────────────────────────────
// A2's u37 (O futuro, o condicional e o infinitivo pessoal) taught the GRAMMAR of
// intention — poder, querer, devia, conseguir, ter de, tentar, será, seria,
// gostaria, é preciso, é melhor — and u20/u23 taught the travel words for booking
// things (reservar, a viagem, o destino). What no unit has taught is the
// vocabulary of a plan as a THING: the plan itself, the diary it sits in, the
// commitment it creates, and the two verbs for cancelling or confirming it.
//
// The pt-PT card that matters most here is `combinar`. English speakers reach for
// "plan to meet" and produce planear, which is wrong in this sense — Portuguese
// arranges things with combinar: combinámos às oito, ficou combinado. Without it
// a learner sounds translated in the most ordinary situation there is.
//
// TWO FAMILIES TRIMMED, per the rule this block follows: planear is carded and
// o planeamento is not; prever is u54's and a previsão is not carded anywhere.
// One lexeme, one card.
