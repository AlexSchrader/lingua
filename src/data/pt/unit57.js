// PT Unit 57 — As emoções e os seus matizes (slot: emotion-fine) — B1
// ─────────────────────────────────────────────────────────────────────────────
// A2's u22 (Os sentimentos e os estados) taught the primary colours of feeling:
// feliz, triste, zangado, contente, nervoso, calmo, a alegria, a raiva, o medo,
// a saudade, o amor, sentir, chorar, rir, sorrir, preocupar-se, adorar, plus the
// ter- states (ter medo, ter pressa, ter sorte). u31 added orgulhoso and u35
// aborrecido. None of that is repeated here.
//
// This unit is the SECOND layer: the feelings that need a situation to explain
// them. Relief only exists after worry, shame after an audience, envy after a
// comparison — which is why every example in this unit has two clauses, and why
// the B1 requirement to write two clauses is not a formatting rule here but the
// content itself. A one-clause example cannot show what a vergonha is.
//
// FAMILIES TRIMMED, same rule as u54: a ansiedade without ansioso, a frustração
// without frustrado, a gratidão without grato. One lexeme gets one card; the
// hint carries the other form.
//
// TWO CARDS ARE PT-PT REGISTER AND EARN THEIR PLACE. `chateado` is the single
// most used mood word in Portugal and does not mean what a dictionary says
// (annoyed, upset, fed up, bored — context decides), and `farto` is how someone
// actually says they have had enough. A learner who knows only zangado from A2
// will sound like a textbook.
//
