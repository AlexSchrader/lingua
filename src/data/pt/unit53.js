// PT Unit 53 — A comparação e o grau (slot: comparison) — B1
// ─────────────────────────────────────────────────────────────────────────────
// A2 already built the comparative MACHINERY and it is not rebuilt here: mais
// (u1), menos / do que / tão / tanto / igual / ambos (u29), melhor (u11),
// bastante / demasiado / quase (u28), a diferença / a vantagem / a maioria (u40),
// o dobro / a metade / o grau (u43). A learner leaving A2 can already say bigger,
// smaller and the same.
//
// What they cannot yet do is compare with PRECISION, and that is this unit: the
// formal pair superior a / inferior a, the language of levels and averages, the
// adverbs that say by how much (ligeiramente, consideravelmente), and the verbs
// of one thing outdoing another. That is the B1 altitude for this slot — the
// scaffold's "Comparison and degree" aimed at A2 would be a second pass over
// mais … do que.
//
// One pt-PT note that shapes several cards: Portuguese prefers a preposition
// where English uses a bare comparative — superior A, inferior A, acima DE,
// abaixo DE — and every one of those fuses with a following article (superior AO
// prazo, acima DA média). The drills keep the bare form so the front survives
// findWholeWord; the examples show the fusion, which is where a learner meets it.
//
// Conventions: pt/unit1.js (language-wide) and pt/unit51.js (this band).
