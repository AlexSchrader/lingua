// PT Unit 63 — A recordação e o hábito (slot: experience-memory) — B1
// ─────────────────────────────────────────────────────────────────────────────
// RE-AIMED, and the last unit of block 1. The scaffold slot is "Experience and
// memory", and both head-words are gone: `a experiência` is taught at u34 (in
// its experiment sense), `a memória` and `o passado` at u48, `a saudade` at u22,
// `lembrar` and `esquecer` at u29, `a história` at u48, `aprender` at u17.
// A unit built on those would teach nothing new.
//
// What is left, and is worth a whole unit, is the machinery AROUND remembering:
// the act of recalling (recordar, reviver, a lembrança), what makes something
// stick (marcante, inesquecível, o cheiro), the habits a life settles into
// (o hábito, o costume, habituar-se, a rotina is u21's), where a person comes
// from (a raiz, o antepassado, familiar, a trajetória), and what experience
// leaves behind (a lição, a prática, o conhecimento, o testemunho).
//
// LEXEME DISCIPLINE, stated once for the record because this unit had the most
// tempting duplicates in the whole block: `relembrar` was rejected (it is
// lembrar, u29, with a prefix), `testemunhar` was rejected in favour of the noun,
// `a recordação` was rejected in favour of `recordar`, and `crescer` was rejected
// here because this block already teaches `o crescimento` at u59. None of the four
// would have been caught by validate:content — all four are distinct strings.
// The test behind each rejection is the one u54's header states: does the second
// card teach anything the first does not? It is a judgement, not an automatic
// ban on a shared root — u80 cards `crescer` under the same test and that is its
// call to make, not a contradiction of this one.
//
// BLOCK 3 BOUNDARY: a infância, a juventude, envelhecer, nascer and a geração
// are lingua-50's at u80 (As fases da vida). This unit touches none of them; the
// two slots are neighbours and the split is chronology (u80) versus recall (u63).
//
// Conventions: pt/unit1.js (language-wide) and pt/unit51.js (this band).
