// PT Unit 59 — A mudança no tempo (slot: describing-change) — B1
// ─────────────────────────────────────────────────────────────────────────────
// A2 built the TIME frame and this unit does not touch it: u28 teaches antes,
// depois, ainda, já, logo, entretanto, às vezes, muitas vezes, raramente,
// normalmente, outra vez, quase, cedo, o momento, o século, a década, durar,
// demorar; u36 adds the imperfect (era, estava, tinha, havia, costumava),
// antigamente, naquele tempo, de repente, enquanto, sempre que, assim que,
// durante, de vez em quando. A learner leaving A2 can place an event in time.
//
// What they cannot do is describe a TREND — something rising, slowing, becoming
// something else, or staying as it is. That is what this unit adds, and it is
// the vocabulary a news item or a report leans on constantly.
//
// `mudar` (u29) is the hinge and is deliberately NOT re-carded. Nor is
// a mudança: it is the same lexeme wearing a noun's coat, and one lexeme gets
// one card (the u54 rule). The unit teaches the words mudar cannot cover —
// direction (aumentar / diminuir), speed (acelerar / abrandar), permanence
// (permanecer / temporário / permanente) and stage (a evolução, o progresso).
//
