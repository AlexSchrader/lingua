// PT Unit 55 — A atualidade e o debate público (slot: news-society) — B1
// ─────────────────────────────────────────────────────────────────────────────
// RE-AIMED, for the same reason u52 was. The scaffold slot is "News and society",
// but pt A2 already spent that ground twice: u32 (A sociedade e a cidadania)
// teaches a notícia, a imprensa, o acontecimento, a greve, o governo, a lei,
// votar, a eleição, o cidadão, o direito, o dever; u19 teaches o jornal and
// a televisão; u33 covers technology and communication. A B1 unit that taught
// "the news" again would be A2 with longer sentences.
//
// So this unit is the LAYER ABOVE the news: where a claim comes from and how it
// is contested. Sources and reporting (a fonte, o relato, apurar, divulgar), the
// public argument itself (o debate, a sondagem, a manifestação, a polémica), the
// attribution frames a reader meets every day (segundo, alegadamente, declarar,
// citar, o porta-voz), and what comes out of it (a medida, a reforma, aprovar).
// Every A2 word listed above appears in the examples and none is re-carded.
//
// BOUNDARY WITH BLOCK 2's u64 (media). u64 owns the MEDIUM — o meio de
// comunicação, the platforms, entertainment. This unit owns the DISCOURSE — who
// said it, on whose authority, and what it set off. o meio de comunicação is
// deliberately ceded to u64 despite this unit having the lower slot number,
// because u64 loses its spine without it and this unit does not.
//
// PT-PT NOTE: `segundo` is carded here as the attribution preposition ("according
// to"), which is a different word from the ordinal already taught at u14
// ("first, second"). Same spelling, same fold, so they would be indistinguishable
// to a typed answer if both were cards — which is exactly why only one is, and
// the hint names the other.
//
