// RE-AIMED, and this one was spent harder than any other slot in the block.
// pt A2's u44 (A lei e os documentos) already teaches a lei, a norma, a regra,
// a licença, a multa, cumprir, o tribunal, o juiz, assinar, a validade,
// a identidade; u32 adds o direito, o dever, respeitar, votar, o imposto;
// u49 adds o pedido, o aviso, o registo and the public-service vocabulary.
// A B1 unit called "Rules" would have been a second pass over u44.
//
// So this unit teaches the DEONTIC LAYER instead — who must, who may, who may
// not, and what happens when they do it anyway. It is modal vocabulary carried
// by nouns and adjectives rather than by a new grammar, exactly as CLAUDE.md
// requires ("grammar has no item type").
//
// NOT CARDED HERE, DELIBERATELY: `dever` as the modal verb. It is block 2's, by
// my own ruling as crew lead — it needs the explicit pair-hint against o dever
// (u32, duty), and the grammar units are where a modal belongs. This unit uses
// ter de (u37) and ser obrigado a instead, which is also what a Portuguese
// speaker actually says.
//
// PT-PT NOTE ON REGISTER: proibido and obrigatório are the words on the signs —
// É proibido fumar, uso obrigatório de máscara. Learning them from a sign is how
// a resident learns them, so several examples here are written as the notice
// itself rather than as a sentence about one.
//
// Conventions: pt/unit1.js (language-wide) and pt/unit51.js (this band).
