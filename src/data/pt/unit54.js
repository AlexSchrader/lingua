// PT Unit 54 — A dúvida e a cautela (slot: hedging) — B1
// ─────────────────────────────────────────────────────────────────────────────
// Hedging is the B1 skill a learner is most likely to be missing entirely, and
// A2 gave them exactly two words for it: talvez (u28) and se calhar (u37). Both
// are spoken, both are all-or-nothing. This unit is the rest of the scale — from
// improvável through é capaz de to quase de certeza — plus the evidential frames
// that say WHERE a claim comes from without committing to it.
//
// Why it matters more in Portuguese than the English gloss suggests: a flat
// assertion is heard as blunter in pt-PT than in English, so a speaker who can
// only say é or não é sounds combative when they mean uncertain. Hedging is the
// register repair for that, and it is why this slot sits next to u51's opinion
// verbs rather than off in a corner.
//
// ONE FAMILY DELIBERATELY TRIMMED. provável / provavelmente / improvável /
// a probabilidade are one lexeme with four costumes; carding all four would be
// four mastery tracks for one piece of learning. The unit keeps the adverb, the
// negative adjective and the noun, and drops the bare positive adjective, which
// the other three teach for free. Same reasoning kept duvidar (L2) and a dúvida
// apart — only the verb is carded; sem dúvida was dropped for afinal.
//
// NOTE FOR BLOCK 2 (u69-u71): several of these frames take the subjunctive in
// natural Portuguese — é possível que SEJA, duvido que VENHA. Every example here
// is deliberately written with the indicative or an infinitive, because the
// subjunctive is not taught until u69 and a B1 unit must not depend on a later
// slot. When u69 lands, these become the obvious revision material for it.
//
// Conventions: pt/unit1.js (language-wide) and pt/unit51.js (this band).
// lang/unit/lesson are stamped in src/data/index.js.
