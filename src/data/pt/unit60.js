// PT Unit 60 — A dificuldade e a solução (slot: problems) — B1
// ─────────────────────────────────────────────────────────────────────────────
// A2 gave the learner `resolver` (u24) and `reclamar` (u27) and very little else
// for trouble: u47 (As emergências e a segurança) covers the acute kind — fire,
// accident, police — and nothing covers the ordinary kind, the problem that sits
// on a desk for three weeks. That is this unit.
//
// The four lessons follow the shape of an actual problem rather than a word
// list: naming it (a dificuldade, o obstáculo, o desafio, a falha, o erro,
// urgente), meeting it (enfrentar, evitar, impedir, lidar com, corrigir,
// remediar), fixing it (a solução, a alternativa, a saída, a melhoria, o apoio,
// o conselho), and the human half — complaining, advising and calming someone
// down (queixar-se, aconselhar, esclarecer, o cuidado, a paciência,
// tranquilizar).
//
// `queixar-se` is carded although `reclamar` (u27) is taught, and the hint makes
// the difference explicit: reclamar is what you do at a shop counter, queixar-se
// is what you do about a situation or a person — and, at the doctor's, about a
// symptom. They are two lexemes, not one in two coats, which is the test this
// block applies before adding any near-synonym.
//
// Conventions: pt/unit1.js (language-wide) and pt/unit51.js (this band).
// lang/unit/lesson are stamped in src/data/index.js.
